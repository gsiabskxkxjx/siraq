  const sk = (s) => S.norm(s).replace(/ا/g, '').replace(/\s+/g, ' ').trim();

  function parseRef(r) { const m = /^(\d+):(\d+)(?:-(\d+))?$/.exec(r); if (!m) return null; return { s: +m[1], a: +m[2], b: +(m[3] || m[2]) }; }
