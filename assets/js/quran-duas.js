      const old = (await S.db.all('duas')).filter((d) => /^qd_/.test(d.id) && !keep.has(d.id));
      for (const d of old) await S.db.del('duas', d.id);
      if (items.length) await S.db.putMany('duas', items);
      await S.kv.set('quranDuas', { key, n: items.length, skipped: QD.skipped.length, at: Date.now() });
      if (QD.skipped.length) S.log('warn', 'أدعية قرآنية أُسقطت لعدم تطابق التحقق: ' + QD.skipped.map((x) => x.ref).join('، '));
